/**
 * Prompt استخراج بيانات الاجتماع — الملف الوحيد المسؤول عن تصميم
 * الـ Prompt، عشان يتعدّل لاحقًا من غير ما نلمس أي منطق برمجي.
 */
export function buildMeetingExtractionPrompt(transcript: string): string {
  return `أنت مساعد يستخرج معلومات عملية من نص تفريغ اجتماع بين فريق ووكالة تطوير.

## النص المفرّغ
${transcript}

## المطلوب منك بالضبط
استخرج من النص أعلاه **JSON فقط** بالشكل التالي بالضبط، بدون أي نص إضافي قبله أو بعده، وبدون Markdown code fences، وبدون أي مفاتيح غير المذكورة:

{
  "decisions": ["قرار تم اتخاذه فعليًا في الاجتماع"],
  "risks": ["مخاطرة أو مصدر قلق ذُكر في الاجتماع"],
  "requests": ["طلب محدد طلبه العميل أو الفريق"],
  "questions": ["سؤال مفتوح لم يُجب عليه في الاجتماع"],
  "deadlines": ["موعد نهائي أو تاريخ محدد ذُكر في الاجتماع"]
}

قواعد صارمة:
- أرجع الكائن JSON فقط، من غير أي شرح أو مقدمة أو خاتمة.
- كل عنصر يجب أن يكون جملة قصيرة وواضحة بنفس لغة النص الأصلي.
- لو مفيش عناصر لفئة معينة، أرجع مصفوفة فاضية [] لها — لا تخترع محتوى غير موجود في النص.
- لا تصنّف نفس العنصر في أكتر من فئة.`;
}
