/**
 * Prompt تحليل مصدر ترحيل — يهذّب تحليلًا **حتميًا جاهزًا** (لا يبدأ من
 * الصفر). الذكاء الاصطناعي يضيف طبقة تفسير بشرية فوق الأرقام: نوع النظام،
 * أهم الوحدات، سرد المخاطر، وما يحتاج مراجعة — بلا اختراع كيانات أو جداول
 * غير موجودة في التحليل المعطى.
 */

const STRICT_RULES = `قواعد صارمة:
- أرجع كائن JSON فقط، بلا أي شرح أو مقدمة أو خاتمة أو Markdown code fences.
- اعتمد **فقط** على التحليل الحتمي المعطى فوق — ممنوع اختراع جداول أو كيانات أو أرقام غير موجودة فيه.
- system_type وصف موجز لنوع النظام القديم بناءً على المجالات والكيانات المكتشَفة.
- key_modules أهم الوحدات الوظيفية المستنتَجة من الكيانات (٣-٨ عناصر).
- risk_narrative فقرة تشرح أخطر ما في المصدر للترحيل، بلغة مدير مشروع.
- human_review_items بنود محدّدة تحتاج قرارًا بشريًا قبل الترحيل.
- migration_readiness_note جملة تفسّر درجة الجاهزية المعطاة (لا تعِد حسابها).
- كل النصوص بالعربية الفصحى الواضحة.`;

const SCHEMA_TEMPLATE = `{
  "system_type": "وصف موجز لنوع النظام القديم",
  "key_modules": ["وحدة وظيفية أساسية مستنتَجة من الكيانات"],
  "risk_narrative": "فقرة تشرح أخطر جوانب المصدر للترحيل",
  "human_review_items": ["بند يحتاج مراجعة/قرار بشري قبل الترحيل"],
  "migration_readiness_note": "جملة تفسّر درجة الجاهزية المعطاة"
}`;

export function buildMigrationSourceAnalysisPrompt(deterministicSummary: string, sourceName: string, sourceType: string): string {
  return `أنت خبير ترحيل أنظمة (Data Migration Architect). مهمتك: قراءة تحليل حتمي جاهز لنظام قديم، وكتابة طبقة تفسير بشرية فوقه تساعد فريق الوكالة يفهم النظام قبل الترحيل. **أنت لا تحلّل قاعدة البيانات من الصفر — التحليل جاهز، أنت تفسّره وتلخّصه.**

## المصدر
الاسم: ${sourceName}
النوع: ${sourceType}

## التحليل الحتمي الجاهز (المصدر الوحيد للحقائق)
${deterministicSummary}

## المطلوب منك بالضبط
أرجع **JSON فقط** بالشكل التالي بالضبط (بلا أي مفتاح إضافي أو مفقود):

${SCHEMA_TEMPLATE}

${STRICT_RULES}`;
}
