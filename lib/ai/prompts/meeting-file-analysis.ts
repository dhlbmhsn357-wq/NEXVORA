/** Prompt تحليل مرفق اجتماع واحد — صورة/PDF (كـ media) أو نص مستخرج من DOCX/CSV (كـ نص مباشر). */
export function buildMeetingFileAnalysisPrompt(title: string, description: string, extractedText: string | null): string {
  const textSection = extractedText
    ? `\n## النص المستخرج من الملف\n${extractedText}\n`
    : "\nالمحتوى مرفق مباشرة كصورة/ملف (راجع الوسائط المرفقة بالطلب).\n";

  return `أنت محلل أعمال بتراجع مرفق اتحمّل في اجتماع مع عميل (وكالة تطوير برمجيات).

## عنوان المرفق
${title}
## وصف المرفق (لو موجود)
${description || "بدون وصف"}
${textSection}
## المطلوب منك بالضبط
أرجع **JSON فقط** بالشكل ده بالظبط، من غير أي نص إضافي أو Markdown code fences:

{
  "summary": "ملخص واضح لمحتوى المرفق وأهميته (فقرة إلى فقرتين)",
  "confidence": 0-100,
  "entities": ["كيان أو معلومة رئيسية مستخرجة من المرفق"]
}

قواعد صارمة:
- لو المحتوى مش واضح أو الملف مش مرتبط بسياق مشروع برمجي، قول كده صراحة في summary وحط confidence منخفض.
- entities: قائمة قصيرة (لحد 10 عناصر) لأهم المعلومات القابلة لإعادة الاستخدام (أسماء وحدات، متطلبات، أرقام، تواريخ).
- كل النصوص بالعربية إلا لو المحتوى الأصلي بالإنجليزية.`;
}
