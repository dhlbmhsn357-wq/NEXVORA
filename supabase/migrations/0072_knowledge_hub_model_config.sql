-- 0072 — إعدادات النماذج لمهام مركز المعرفة والزيادات
--
-- المشكلة: `ai_task_model_config` بيتقرأ منه إعداد النموذج لكل نوع مهمة،
-- وأي نوع جديد بيتضاف في الكود من غير صف هنا كان بيفشل بالكامل برسالة
-- "لا يوجد إعداد Model لهذا النوع من المهام".
--
-- خمس مهام كانت ناقصة: أربعة من مركز المعرفة وواحدة من أقسام PRD
-- للزيادات.
--
-- ملاحظة: الكود بقى بيرجع لإعداد افتراضي (أشيع إعداد مستخدم في الجدول)
-- بدل ما يفشل، فالمهام شغالة حتى قبل الهجرة دي. الهجرة بتديك التحكّم:
-- بعدها تقدر تغيّر النموذج لكل مهمة من تبويب الإعدادات.
--
-- الهجرة إضافية بالكامل، و`on conflict do nothing` بيخلّيها آمنة لو
-- اتشغّلت أكتر من مرة أو لو ضبطت النموذج يدويًا قبل كده.

insert into public.ai_task_model_config (task_type, provider, model)
values
  -- تصنيف مقطع مستند لعناصر معرفة + فجوات. بيستقبل الملف نفسه أحيانًا
  -- (PDF/صورة/صوت) فمحتاج موديل بيقرا وسائط.
  ('knowledge_classification', 'gemini', 'gemini-3.5-flash'),
  -- الإثراء والربط: علاقات + تعارضات + مصطلحات داخل تصنيف واحد.
  ('knowledge_enrichment', 'gemini', 'gemini-3.5-flash'),
  -- التوليف: تحويل المعرفة لعناصر جاهزة للـ Brain + بنى تشغيلية.
  ('knowledge_synthesis', 'gemini', 'gemini-3.5-flash'),
  -- التحقق المتقاطع بين المستندات وكلام العميل وقرارات الاجتماعات.
  ('knowledge_cross_validation', 'gemini', 'gemini-3.5-flash'),
  -- قسم PRD مخصّص لزيادة واحدة.
  ('prd_increment_section', 'gemini', 'gemini-3.5-flash')
on conflict (task_type) do nothing;
